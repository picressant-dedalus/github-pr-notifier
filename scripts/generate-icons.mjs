// Generates the extension icons (img/icon*.png) and the inline SVG module (js/icons.js)
// from GitHub Octicons (MIT licensed, devDependency @primer/octicons).
// Run with: npm run icons
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const svgDir = join(root, 'node_modules/@primer/octicons/build/svg');
const read = (name) => readFileSync(join(svgDir, `${name}.svg`), 'utf8');

// Toolbar / store icons: black GitHub mark on transparent background
const mark = read('mark-github-24').replace('<svg ', '<svg fill="#24292f" ');
for (const size of [16, 32, 48, 128]) {
  await sharp(Buffer.from(mark), { density: 72 * size / 24 * 4 })
    .resize(size, size)
    .png()
    .toFile(join(root, `img/icon${size}.png`));
}

const icons = {
  github: 'mark-github-24',
  check: 'check-circle-fill-16',
  cross: 'x-circle-fill-16',
  dot: 'dot-fill-16',
  flag: 'flag-16',
  sync: 'sync-16',
  gear: 'gear-16',
  merge: 'git-merge-16',
  clock: 'clock-16',
  branch: 'git-branch-16',
  pullRequest: 'git-pull-request-16',
  alert: 'alert-16'
};

const entries = Object.entries(icons).map(([key, file]) => {
  const svg = read(file)
    .replace(/\s*\n\s*/g, '')
    .replace(/(<svg[^>]*?)\s+fill="[^"]*"/, '$1')
    .replace('<svg ', '<svg class="octicon" aria-hidden="true" fill="currentColor" ')
    .trim();
  return `  ${key}: ${JSON.stringify(svg)}`;
});

writeFileSync(join(root, 'js/icons.js'), `// GENERATED by scripts/generate-icons.mjs from @primer/octicons (MIT) - do not edit by hand.
export const ICONS = {
${entries.join(',\n')}
};
`);
console.log('Icons generated');
